const bySlug = new Map(countries.map((country) => [country.slug, country]))
const byCode = new Map(countries.map((country) => [country.code, country]))

export function getCountry(slug: string) {
  return bySlug.get(slug)
}

export function isCountrySlug(slug: string): slug is string {
  return bySlug.has(slug)
}

export function getCountryByCode(code: string) {
  return byCode.get(code.toUpperCase())
}

export function countrySlugs() {
  return countries.map((country) => country.slug)
}

export function countriesByRegion() {
  const groups = new Map<string, Country[]>()
  for (const country of countries) {
    const list = groups.get(country.region)
    if (list) list.push(country)
    else groups.set(country.region, [country])
  }
  return [...groups.entries()].sort(([a], [b]) => a.localeCompare(b, 'en'))
}
